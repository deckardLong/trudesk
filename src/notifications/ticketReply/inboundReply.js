/*
 * Xử lý email người dùng TRẢ LỜI thông báo ticket (chiều ngược lại của kênh email).
 *
 * Luồng: người dùng bấm Reply -> thư tới support+t1042.<sig>@... -> mailCheck (IMAP) đọc ->
 *        resolveInboundReply() quyết định:
 *
 *   'new_ticket' : không có token / token sai / ticket không tồn tại -> hành vi cũ (tạo ticket mới)
 *   'ignore'     : thư tự động (auto-reply, vắng mặt, bounce) -> bỏ qua, tránh vòng lặp mail
 *   'reject'     : người gửi không phải owner/subscriber, hoặc nội dung rỗng -> không ghi gì
 *   'comment'    : thêm comment vào ticket đang mở
 *   'reopen'     : ticket đã đóng trong cửa sổ reopenWindowDays -> thêm comment + mở lại
 *   'new_ticket' (kèm relatedTicketUid) : ticket đã đóng quá lâu -> tạo ticket mới, tham chiếu ticket cũ
 */

const { findTokenInAddresses } = require('./replyToken')
const { REPLY_MARKER } = require('./emailComposer')
const { idOf } = require('./recipientResolver')

const QUOTE_HEADERS = [
  new RegExp('^\\s*' + REPLY_MARKER.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')),
  /^\s*On .+wrote:\s*$/i,
  /^\s*Vào .+đã viết:\s*$/i,
  /^\s*-{2,}\s*Original Message\s*-{2,}/i,
  /^\s*From:\s.+/i,
  /^\s*Từ:\s.+/i,
  /^\s*_{10,}\s*$/,
  /^--\s*$/ // chữ ký email chuẩn "-- "
]

/** Giữ lại phần người dùng mới viết, bỏ lịch sử trích dẫn và chữ ký. */
function extractReplyText (text) {
  const lines = String(text || '').replace(/\r\n/g, '\n').split('\n')
  const kept = []
  for (const line of lines) {
    if (QUOTE_HEADERS.some(re => re.test(line))) break
    if (/^\s*>/.test(line)) continue
    kept.push(line)
  }
  return kept.join('\n').replace(/\n{3,}/g, '\n\n').trim()
}

function isAutoGenerated (headers) {
  const h = headers || {}
  const autoSubmitted = String(h['auto-submitted'] || '').toLowerCase()
  if (autoSubmitted && autoSubmitted !== 'no') return true
  const precedence = String(h.precedence || '').toLowerCase()
  if (['bulk', 'junk', 'list', 'auto_reply'].indexOf(precedence) !== -1) return true
  if (h['x-autoreply'] || h['x-autorespond']) return true
  return false
}

/**
 * @param {Object} mail
 * @param {String}   mail.from        địa chỉ người gửi
 * @param {String[]} mail.to          tất cả địa chỉ nhận (To + Cc + Delivered-To)
 * @param {String}   mail.text        nội dung dạng text
 * @param {Object}   [mail.headers]   header đã chuẩn hóa chữ thường
 * @param {Object} deps
 * @param {String}   deps.secret
 * @param {Function} deps.findTicketByUid  async uid -> ticket | null
 *                    (ticket có owner, subscribers dạng { _id, email }, status.isResolved, closedDate)
 * @param {Number}   [deps.reopenWindowDays=7]
 * @param {Function} [deps.now]
 */
async function resolveInboundReply (mail, deps) {
  const reopenWindowDays = deps.reopenWindowDays == null ? 7 : deps.reopenWindowDays
  const now = deps.now ? deps.now() : Date.now()

  if (isAutoGenerated(mail.headers)) return { action: 'ignore', reason: 'auto-generated' }

  const token = findTokenInAddresses(mail.to, deps.secret)
  if (!token) return { action: 'new_ticket', reason: 'no-valid-token' }

  const ticket = await deps.findTicketByUid(token.uid)
  if (!ticket || ticket.deleted) return { action: 'new_ticket', reason: 'ticket-not-found' }

  const from = String(mail.from || '').trim().toLowerCase()
  const participants = [ticket.owner, ticket.assignee].concat(ticket.subscribers || []).filter(Boolean)
  const sender = participants.find(p => p.email && String(p.email).toLowerCase() === from)
  if (!sender) return { action: 'reject', reason: 'sender-not-participant', ticketUid: ticket.uid }

  const body = extractReplyText(mail.text)
  if (!body) return { action: 'reject', reason: 'empty-body', ticketUid: ticket.uid }

  const base = { ticket, ticketUid: ticket.uid, senderId: idOf(sender), body }

  const isClosed = ticket.status && ticket.status.isResolved
  if (!isClosed) return { ...base, action: 'comment' }

  const closedAt = ticket.closedDate ? new Date(ticket.closedDate).getTime() : now
  const daysClosed = (now - closedAt) / (24 * 60 * 60 * 1000)
  if (daysClosed <= reopenWindowDays) return { ...base, action: 'reopen' }

  return { ...base, action: 'new_ticket', reason: 'closed-too-long', relatedTicketUid: ticket.uid }
}

module.exports = { resolveInboundReply, extractReplyText, isAutoGenerated }
